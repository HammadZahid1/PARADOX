/** Markdown rendering for deterministic, shareable simulation reports. */

export type ReportSeverity = 'info' | 'notice' | 'warning' | 'critical';

export interface ReportMetadata {
  readonly title: string;
  readonly scenarioName: string;
  readonly seed: number;
  readonly steps: number;
  readonly generatedBy?: string;
  readonly tags?: readonly string[];
}

export type ReportValue = number | string | boolean;

export interface ReportMetric {
  readonly name: string;
  readonly value: ReportValue;
  readonly unit?: string;
  readonly delta?: number;
}

export interface ReportEvent {
  readonly step: number;
  readonly name: string;
  readonly severity?: ReportSeverity;
  readonly detail?: string;
}

export interface SimulationReport {
  readonly metadata: ReportMetadata;
  readonly summary?: string;
  readonly metrics: readonly ReportMetric[];
  readonly events?: readonly ReportEvent[];
}

/** Escape text used in headings, lists and table cells. */
export function escapeMarkdownText(text: string): string {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/([`*_[\]<>`|])/g, '\\$1');
}

export function escapeMarkdownCell(text: string): string {
  return escapeMarkdownText(text).replace(/\r\n|\n|\r/g, '<br>');
}

function formatValue(value: ReportValue): string {
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'n/a';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  return escapeMarkdownCell(value);
}

function formatDelta(delta: number): string {
  if (!Number.isFinite(delta)) return 'n/a';
  return `${delta > 0 ? '+' : ''}${delta}`;
}

function renderTable(headers: readonly string[], rows: readonly (readonly string[])[]): string[] {
  const lines = [
    `| ${headers.map(escapeMarkdownCell).join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
  ];
  for (const row of rows) lines.push(`| ${row.join(' | ')} |`);
  return lines;
}

export function renderReportMarkdown(report: SimulationReport): string {
  const metadata = report.metadata;
  const lines: string[] = [
    `# ${escapeMarkdownText(metadata.title)}`,
    '',
    '## Metadata',
    '',
    `- Scenario: ${escapeMarkdownText(metadata.scenarioName)}`,
    `- Seed: ${formatValue(metadata.seed)}`,
    `- Steps: ${formatValue(metadata.steps)}`,
  ];
  if (metadata.generatedBy !== undefined) {
    lines.push(`- Generated by: ${escapeMarkdownText(metadata.generatedBy)}`);
  }
  if (metadata.tags !== undefined) {
    lines.push(`- Tags: ${metadata.tags.map(escapeMarkdownText).join(', ') || 'none'}`);
  }

  if (report.summary !== undefined) {
    lines.push('', '## Summary', '', escapeMarkdownText(report.summary));
  }

  lines.push('', '## Metrics', '');
  if (report.metrics.length === 0) {
    lines.push('_No metrics recorded._');
  } else {
    lines.push(
      ...renderTable(
        ['Metric', 'Value', 'Delta'],
        report.metrics.map((metric) => [
          formatValue(metric.name),
          metric.unit === undefined
            ? formatValue(metric.value)
            : `${formatValue(metric.value)} ${escapeMarkdownCell(metric.unit)}`,
          metric.delta === undefined ? '—' : formatDelta(metric.delta),
        ]),
      ),
    );
  }

  if (report.events !== undefined) {
    lines.push('', '## Events', '');
    if (report.events.length === 0) {
      lines.push('_No events recorded._');
    } else {
      lines.push(
        ...renderTable(
          ['Step', 'Event', 'Severity', 'Detail'],
          report.events.map((event) => [
            formatValue(event.step),
            formatValue(event.name),
            event.severity === undefined ? '—' : escapeMarkdownCell(event.severity),
            event.detail === undefined ? '—' : formatValue(event.detail),
          ]),
        ),
      );
    }
  }

  return `${lines.join('\n')}\n`;
}
